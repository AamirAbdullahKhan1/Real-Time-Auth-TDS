CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL UNIQUE,
    password_hash text NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES users(id) ON DELETE SET NULL,
    username text,
    email text,
    event_type text NOT NULL,
    risk_label text NOT NULL,
    severity text NOT NULL,
    detected_rule text,
    ip_address text,
    country text,
    user_agent text,
    details jsonb NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS auth_events_account_time_idx
    ON auth_events (user_id, created_at DESC, id DESC);
CREATE TABLE IF NOT EXISTS auth_sessions (
    id uuid PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at timestamptz;

CREATE TABLE IF NOT EXISTS auth_email_challenges (
    id uuid PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose text NOT NULL CHECK (purpose IN ('register', 'login')),
    code_digest text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    failed_attempts integer NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 5),
    consumed_at timestamptz,
    invalidated_at timestamptz
);

CREATE INDEX IF NOT EXISTS auth_email_challenges_account_time_idx
    ON auth_email_challenges (user_id, created_at DESC);

ALTER TABLE auth_sessions ADD COLUMN IF NOT EXISTS email_challenge_id uuid
    UNIQUE REFERENCES auth_email_challenges(id);
ALTER TABLE users ADD COLUMN IF NOT EXISTS role text NOT NULL DEFAULT 'customer'
    CHECK (role IN ('admin', 'employee', 'customer'));

ALTER TABLE auth_events ADD COLUMN IF NOT EXISTS account_role text
    CHECK (account_role IN ('admin', 'employee', 'customer'));

ALTER TABLE auth_email_challenges DROP CONSTRAINT IF EXISTS auth_email_challenges_purpose_check;
ALTER TABLE auth_email_challenges ADD CONSTRAINT auth_email_challenges_purpose_check
    CHECK (purpose IN ('register', 'login', 'password_reset'));
ALTER TABLE users
    ADD COLUMN IF NOT EXISTS password_failures integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS last_password_failure_at timestamptz,
    ADD COLUMN IF NOT EXISTS auth_locked_until timestamptz;
